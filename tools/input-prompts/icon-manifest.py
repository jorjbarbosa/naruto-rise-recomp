"""Builds the manifest of the game's button icons for the native renderer.

usage: python -I tools/input-prompts/icon-manifest.py <game folder with Naruto_clip.SRA>

tools/input-prompts/game-icons.json names, by the resource name of each DDS
image of Naruto_clip.SRA, the controller input it shows (labelled from the
contact sheets of the 2026-11-02 inventory). This writes
app/src/gpu/textures/button_icons.inc: per image, the FNV-1a 64 of its first
level's DXT5 blocks (what the renderer reads back, untiled and in host byte
order), its size and its input. Only hashes and names: no game content.
"""
import json
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def fnv64(data):
    h = 0xCBF29CE484222325
    for byte in data:
        h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    labels = json.loads((ROOT / 'tools/input-prompts/game-icons.json').read_text(encoding='utf8'))
    archive = (Path(sys.argv[1]) / 'Naruto_clip.SRA').read_bytes()
    magic, version, index_offset, count, names_offset, names_count = struct.unpack_from('<4s5I', archive)
    assert magic == b'FRSA' and version == 1
    record = (len(archive) - names_offset) // names_count
    names = {}
    for i in range(names_count):
        at = names_offset + record * i
        _, kind, key = struct.unpack_from('<3I', archive, at)
        names[(kind, key)] = archive[at + 12:at + 140].split(b'\0')[0].decode('latin1')
    rows, found = [], set()
    for i in range(count):
        kind, key, _, offset, packed, _, _ = struct.unpack_from('<7I', archive, index_offset + i * 28)
        name = names.get((kind, key))
        if kind != 2 or name not in labels:
            continue
        dds = zlib.decompress(archive[offset:offset + packed])
        height, width = struct.unpack_from('<II', dds, 12)
        assert dds[:4] == b'DDS ' and dds[84:88] == b'DXT5', name
        size = ((width + 3) // 4) * ((height + 3) // 4) * 16
        rows.append((fnv64(dds[128:128 + size]), width, height, labels[name], name))
        found.add(name)
    missing = sorted(set(labels) - found)
    assert not missing, missing
    unique = sorted({row[:4] for row in rows})
    lines = ['// Generated by tools/input-prompts/icon-manifest.py: the button icons of',
             '// Naruto_clip.SRA by the FNV-1a 64 of their first level (DXT5 blocks).',
             '// {hash, width, height, input}']
    lines += [f'{{0x{h:016x}ull, {w}, {hh}, "{label}"}},' for h, w, hh, label in unique]
    (ROOT / 'app/src/gpu/textures/button_icons.inc').write_text('\n'.join(lines) + '\n', encoding='utf8', newline='\n')
    print(len(rows), 'images,', len(unique), 'distinct')


main()
