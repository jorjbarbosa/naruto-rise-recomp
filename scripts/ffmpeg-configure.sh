#!/bin/sh
# Regenerates cmake/ffmpeg/linux: the FFmpeg configuration of the XMA decoder for Linux x64, the
# counterpart of ffmpeg-configure.ps1 (which writes cmake/ffmpeg/windows).
#
# The runtime builds only the part of FFmpeg its XMA1 decoder needs (libavutil and libavcodec with the
# xma1 decoder), with CMake instead of FFmpeg's make. This script runs FFmpeg's configure once with
# clang and keeps what the build needs: the generated headers and codec lists, and the source files
# make would compile (sources.cmake). Run it after updating thirdparty/ffmpeg; the output is checked in.
#
#   ./scripts/ffmpeg-configure.sh
set -u

. "$(dirname "$0")/common.sh"

ffmpeg="$repo_root/thirdparty/ffmpeg"
output="$repo_root/cmake/ffmpeg/linux"
[ -f "$ffmpeg/configure" ] || fail 'thirdparty/ffmpeg is empty; run: git submodule update --init'
command -v clang >/dev/null 2>&1 || fail 'clang not found'

work=$(mktemp -d) || fail 'could not make a temporary folder'
trap 'rm -rf "$work"' EXIT

# FFmpeg is only called under the XMA decoder's lock (src/apu/xma.cpp), from one thread at a time.
(cd "$work" && "$ffmpeg/configure" --cc=clang --cxx=clang++ --target-os=linux --arch=x86_64 \
    --disable-all --disable-everything --disable-autodetect --disable-asm \
    --disable-debug --disable-doc --disable-network \
    --disable-pthreads --disable-w32threads --disable-os2threads \
    --enable-static --disable-shared --enable-avcodec --enable-avutil \
    --enable-decoder=xma1 >configure.log 2>&1) || {
    # The temporary folder goes when the script ends: keep the log.
    mkdir -p "$repo_root/build" && cp "$work/configure.log" "$repo_root/build/ffmpeg-configure.log" ||
        fail 'FFmpeg configure failed, and its log could not be kept'
    fail 'FFmpeg configure failed; see build/ffmpeg-configure.log'
}

{ rm -rf "$output" && mkdir -p "$output/libavutil" "$output/libavcodec"; } || fail "could not recreate $output"

# Generated files the sources include.
for file in config.h config_components.h libavutil/avconfig.h \
    libavcodec/codec_list.c libavcodec/parser_list.c libavcodec/bsf_list.c; do
    cp "$work/$file" "$output/$file" || fail "configure wrote no $file"
done
# Written by make (ffbuild/version.sh) in a normal build.
version=$(git -C "$ffmpeg" describe --tags --always) && [ -n "$version" ] ||
    fail 'git cannot describe thirdparty/ffmpeg'
cat >"$output/libavutil/ffversion.h" <<EOF
/* Generated by scripts/ffmpeg-configure.sh */
#ifndef AVUTIL_FFVERSION_H
#define AVUTIL_FFVERSION_H
#define FFMPEG_VERSION "$version"
#endif /* AVUTIL_FFVERSION_H */
EOF

# The objects make would build: OBJS and STLIBOBJS of each library, unconditional or under an enabled
# CONFIG_/HAVE_ variable of config.mak.
{
    echo '# Generated by scripts/ffmpeg-configure.sh: the FFmpeg sources of the XMA decoder build,'
    echo '# relative to thirdparty/ffmpeg.'
    for library in libavutil libavcodec; do
        name=$(echo "${library#lib}" | tr '[:lower:]' '[:upper:]')
        echo "set(FFMPEG_${name}_SOURCES"
        sed -e ':a' -e '/\\$/N; s/\\\n/ /; ta' "$ffmpeg/$library/Makefile" |
            awk -v enabled="$work/ffbuild/config.mak" -v library="$library" -v root="$ffmpeg" '
                BEGIN {
                    while ((getline line < enabled) > 0)
                        if (line ~ /^[A-Za-z0-9_]+=yes$/) { sub(/=yes$/, "", line); on[line] = 1 }
                }
                match($0, /^(OBJS|STLIBOBJS)(-\$\([A-Za-z0-9_]+\))?[ \t]*\+?=/) {
                    head = substr($0, 1, RLENGTH)
                    rest = substr($0, RLENGTH + 1)
                    if (match(head, /\$\([A-Za-z0-9_]+\)/)) {
                        variable = substr(head, RSTART + 2, RLENGTH - 3)
                        if (!(variable in on)) next
                    }
                    count = split(rest, objects, /[ \t]+/)
                    for (i = 1; i <= count; i++) {
                        if (objects[i] !~ /\.o$/) continue
                        file = library "/" substr(objects[i], 1, length(objects[i]) - 2) ".c"
                        if (file in seen) continue
                        if ((getline probe < (root "/" file)) < 0) continue
                        close(root "/" file)
                        seen[file] = 1
                        print "    " file
                    }
                }'
        echo ')'
    done
} >"$output/sources.cmake" || fail 'could not write sources.cmake'

echo "wrote $output (FFmpeg $version)"
