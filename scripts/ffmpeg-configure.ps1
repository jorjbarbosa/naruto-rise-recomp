<#
.SYNOPSIS
    Regenerates cmake/ffmpeg: the FFmpeg configuration for the XMA decoder.

.DESCRIPTION
    The runtime builds only the part of FFmpeg its XMA1 decoder needs (libavutil and libavcodec
    with the xma1 decoder), with CMake instead of FFmpeg's make. This script runs FFmpeg's
    configure once, through the bash of Git for Windows and with clang-cl, and keeps what the build
    needs: the generated headers and codec lists, and the source files make would compile
    (sources.cmake). Run it after updating thirdparty/ffmpeg; the output is checked in.

.EXAMPLE
    ./scripts/ffmpeg-configure.ps1
#>

. "$PSScriptRoot/common.ps1"

$bash = Join-Path $env:ProgramFiles 'Git/bin/bash.exe'
if (-not (Test-Path $bash)) { Fail "the bash of Git for Windows was not found at $bash" }
$ffmpeg = Join-Path $RepoRoot 'thirdparty/ffmpeg'
if (-not (Test-Path (Join-Path $ffmpeg 'configure'))) { Fail 'thirdparty/ffmpeg is empty; run: git submodule update --init' }
$output = Join-Path $RepoRoot 'cmake/ffmpeg'

Use-VsDevEnvironment

$work = Join-Path ([IO.Path]::GetTempPath()) "roan-ffmpeg-configure-$PID"
New-Item -ItemType Directory -Force $work | Out-Null
try {
    # configure runs in a POSIX shell: it wants /c/... paths.
    $source = '/' + ($ffmpeg -replace '\\', '/' -replace ':', '')
    $options = @(
        '--toolchain=msvc', '--cc=clang-cl', '--cxx=clang-cl', '--ld=lld-link',
        '--target-os=win64', '--arch=x86_64',
        '--disable-all', '--disable-everything', '--disable-autodetect', '--disable-asm',
        '--disable-debug', '--disable-doc', '--disable-network',
        # FFmpeg is only called under the XMA decoder's lock (src/apu/xma.cpp), from one thread at a time.
        '--disable-pthreads', '--disable-w32threads', '--disable-os2threads',
        '--enable-static', '--disable-shared', '--enable-avcodec', '--enable-avutil',
        '--enable-decoder=xma1')
    Push-Location $work
    & $bash -c "$source/configure $($options -join ' ') > configure.log 2>&1"
    $status = $LASTEXITCODE
    Pop-Location
    if ($status -ne 0) { Fail "FFmpeg configure failed; see $work/configure.log" }

    # Generated files the sources include.
    $generated = @('config.h', 'config_components.h', 'libavutil/avconfig.h',
        'libavcodec/codec_list.c', 'libavcodec/parser_list.c', 'libavcodec/bsf_list.c')
    foreach ($file in $generated) {
        $target = Join-Path $output $file
        New-Item -ItemType Directory -Force (Split-Path -Parent $target) | Out-Null
        Copy-Item (Join-Path $work $file) $target
    }
    # Written by make (ffbuild/version.sh) in a normal build.
    $version = (git -C $ffmpeg describe --tags --always).Trim()
    Set-Content -Path (Join-Path $output 'libavutil/ffversion.h') -Encoding ascii -Value @(
        '/* Generated by scripts/ffmpeg-configure.ps1 */',
        '#ifndef AVUTIL_FFVERSION_H',
        '#define AVUTIL_FFVERSION_H',
        "#define FFMPEG_VERSION `"$version`"",
        '#endif /* AVUTIL_FFVERSION_H */')

    # The objects make would build: OBJS and STLIBOBJS of each library, unconditional or under an
    # enabled CONFIG_/HAVE_ variable of config.mak.
    $enabled = @{}
    foreach ($line in Get-Content (Join-Path $work 'ffbuild/config.mak')) {
        if ($line -match '^(\w+)=yes$') { $enabled[$Matches[1]] = $true }
    }
    $lists = @()
    foreach ($library in 'libavutil', 'libavcodec') {
        $text = (Get-Content -Raw (Join-Path $ffmpeg "$library/Makefile")) -replace '\\\r?\n', ' '
        $sources = [System.Collections.Generic.List[string]]::new()
        foreach ($line in $text -split '\r?\n') {
            if ($line -notmatch '^(OBJS|STLIBOBJS)(-\$\((\w+)\))?\s*\+?=\s*(.*)$') { continue }
            if ($Matches[3] -and -not $enabled[$Matches[3]]) { continue }
            foreach ($object in $Matches[4] -split '\s+') {
                if (-not $object.EndsWith('.o')) { continue }
                $file = "$library/$($object.Substring(0, $object.Length - 2)).c"
                if ((Test-Path (Join-Path $ffmpeg $file)) -and -not $sources.Contains($file)) { $sources.Add($file) }
            }
        }
        $name = 'FFMPEG_' + $library.Substring(3).ToUpper() + '_SOURCES'
        $lists += "set($name"
        $lists += $sources | ForEach-Object { "    $_" }
        $lists += ')'
    }
    Set-Content -Path (Join-Path $output 'sources.cmake') -Encoding ascii -Value (@(
        '# Generated by scripts/ffmpeg-configure.ps1: the FFmpeg sources of the XMA decoder build,',
        '# relative to thirdparty/ffmpeg.') + $lists)
    Write-Host "wrote $output (FFmpeg $version)"
}
finally {
    Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
}
